package com.example.myapplication.viewmodel

import android.app.Application
import androidx.lifecycle.AndroidViewModel
import androidx.lifecycle.viewModelScope
import com.example.myapplication.data.algorithm.AlgorithmType
import com.example.myapplication.data.algorithm.CodeLanguage
import com.example.myapplication.data.algorithm.CodeTemplateRegistry
import com.example.myapplication.data.algorithm.CodeValidationResult
import com.example.myapplication.data.algorithm.CodeValidator
import com.example.myapplication.data.algorithm.ExecutionEngine
import com.example.myapplication.data.algorithm.ExecutionFrame
import com.example.myapplication.data.algorithm.InputValidator
import com.example.myapplication.data.algorithm.ValidationResult
import com.example.myapplication.data.algorithm.VizStep
import com.example.myapplication.data.model.request.VisualizerAiRequest
import com.example.myapplication.data.model.response.VisualizerAiData
import com.example.myapplication.data.repository.LearningRepository
import com.example.myapplication.data.repository.VisualizerAiRepository
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.launch
import kotlin.random.Random

// Backward compatibility typealias for screen
typealias VizStepState = VizStep

data class AlgorithmMeta(
    val name: String,
    val slug: String,
    val timeComplexity: String,
    val spaceComplexity: String,
    val complexityNote: String,
    val codeLines: List<String>
)

class VisualizerViewModel(application: Application) : AndroidViewModel(application) {
    private val learningRepository = LearningRepository(application)
    private val aiRepository = VisualizerAiRepository(application)

    private val _selectedAlg = MutableStateFlow(0) // 0: Binary Search, 1: Bubble Sort, 2: Two Pointers
    val selectedAlg: StateFlow<Int> = _selectedAlg.asStateFlow()

    private val _currentLanguage = MutableStateFlow(CodeLanguage.KOTLIN)
    val currentLanguage: StateFlow<CodeLanguage> = _currentLanguage.asStateFlow()

    private val _editableCode = MutableStateFlow("")
    val editableCode: StateFlow<String> = _editableCode.asStateFlow()

    private val _currentStepIdx = MutableStateFlow(0)
    val currentStepIdx: StateFlow<Int> = _currentStepIdx.asStateFlow()

    private val _isPlaying = MutableStateFlow(false)
    val isPlaying: StateFlow<Boolean> = _isPlaying.asStateFlow()

    private val _speed = MutableStateFlow(1f) // 0.5f, 1f, 2f
    val speed: StateFlow<Float> = _speed.asStateFlow()

    // Dynamic execution frames generated by ExecutionEngine
    private val _executionFrames = MutableStateFlow<List<ExecutionFrame>>(emptyList())
    val executionFrames: StateFlow<List<ExecutionFrame>> = _executionFrames.asStateFlow()

    // Custom input editing state
    private val _isInputEditorOpen = MutableStateFlow(false)
    val isInputEditorOpen: StateFlow<Boolean> = _isInputEditorOpen.asStateFlow()

    private val _customArrayInput = MutableStateFlow("")
    val customArrayInput: StateFlow<String> = _customArrayInput.asStateFlow()

    private val _customTargetInput = MutableStateFlow("")
    val customTargetInput: StateFlow<String> = _customTargetInput.asStateFlow()

    private val _inputError = MutableStateFlow<String?>(null)
    val inputError: StateFlow<String?> = _inputError.asStateFlow()

    private val _codeStatusMessage = MutableStateFlow<String?>(null)
    val codeStatusMessage: StateFlow<String?> = _codeStatusMessage.asStateFlow()

    // Working dataset per algorithm
    private var currentBsArray = listOf(2, 5, 8, 12, 16, 23, 38, 56, 72, 91)
    private var currentBsTarget = 23

    private var currentBubbleArray = listOf(25, 12, 8, 34, 19, 6)

    private var currentTpArray = listOf(1, 3, 4, 7, 10, 14, 18, 22)
    private var currentTpTarget = 17

    // Gemini AI Ally state
    private val _isAiSheetOpen = MutableStateFlow(false)
    val isAiSheetOpen: StateFlow<Boolean> = _isAiSheetOpen.asStateFlow()

    private val _aiLoading = MutableStateFlow(false)
    val aiLoading: StateFlow<Boolean> = _aiLoading.asStateFlow()

    private val _aiResponse = MutableStateFlow<VisualizerAiData?>(null)
    val aiResponse: StateFlow<VisualizerAiData?> = _aiResponse.asStateFlow()

    private val _aiError = MutableStateFlow<String?>(null)
    val aiError: StateFlow<String?> = _aiError.asStateFlow()

    private val _selectedAiAction = MutableStateFlow("EXPLAIN_STEP")
    val selectedAiAction: StateFlow<String> = _selectedAiAction.asStateFlow()

    private var autoPlayJob: Job? = null

    // Algorithm metadata definitions
    val algMetadata = listOf(
        AlgorithmMeta(
            name = "Binary Search",
            slug = "binary-search",
            timeComplexity = "O(log N)",
            spaceComplexity = "O(1)",
            complexityNote = "Halves search interval each iteration",
            codeLines = emptyList()
        ),
        AlgorithmMeta(
            name = "Bubble Sort",
            slug = "bubble-sort",
            timeComplexity = "O(N^2)",
            spaceComplexity = "O(1)",
            complexityNote = "Adjacent pair swaps with settling passes",
            codeLines = emptyList()
        ),
        AlgorithmMeta(
            name = "Two Pointers",
            slug = "two-pointers",
            timeComplexity = "O(N)",
            spaceComplexity = "O(1)",
            complexityNote = "Inward converging scan on sorted collection",
            codeLines = emptyList()
        )
    )

    init {
        loadTemplateForCurrentSelection()
        updateInputTextFields()
        runAndVisualizeCode()
    }

    private fun getAlgorithmType(idx: Int = _selectedAlg.value): AlgorithmType {
        return when (idx) {
            0 -> AlgorithmType.BINARY_SEARCH
            1 -> AlgorithmType.BUBBLE_SORT
            else -> AlgorithmType.TWO_POINTERS
        }
    }

    private fun loadTemplateForCurrentSelection() {
        val template = CodeTemplateRegistry.getTemplate(getAlgorithmType(), _currentLanguage.value)
        _editableCode.value = template.defaultCode
    }

    private fun updateInputTextFields() {
        when (_selectedAlg.value) {
            0 -> {
                _customArrayInput.value = currentBsArray.joinToString(", ")
                _customTargetInput.value = currentBsTarget.toString()
            }
            1 -> {
                _customArrayInput.value = currentBubbleArray.joinToString(", ")
                _customTargetInput.value = ""
            }
            else -> {
                _customArrayInput.value = currentTpArray.joinToString(", ")
                _customTargetInput.value = currentTpTarget.toString()
            }
        }
        _inputError.value = null
    }

    fun selectAlgorithm(idx: Int) {
        if (_selectedAlg.value == idx) return
        _selectedAlg.value = idx
        _isInputEditorOpen.value = false
        loadTemplateForCurrentSelection()
        updateInputTextFields()
        runAndVisualizeCode()
    }

    fun setLanguage(language: CodeLanguage) {
        if (_currentLanguage.value == language) return
        _currentLanguage.value = language
        loadTemplateForCurrentSelection()
        runAndVisualizeCode()
    }

    fun onCodeEdited(newCode: String) {
        _editableCode.value = newCode
    }

    fun resetCodeToTemplate() {
        loadTemplateForCurrentSelection()
        _codeStatusMessage.value = "Reset to standard ${_currentLanguage.value.displayName} template."
        runAndVisualizeCode()
    }

    /**
     * Executes real algorithm using ExecutionEngine, synchronizing code lines and visual frames.
     */
    fun runAndVisualizeCode() {
        pause()
        val algType = getAlgorithmType()
        val lang = _currentLanguage.value
        val code = _editableCode.value

        // Validate code pattern
        when (val vRes = CodeValidator.validateCode(code, algType, lang)) {
            is CodeValidationResult.Valid -> {
                _codeStatusMessage.value = if (vRes.customNotes.isNotEmpty()) vRes.customNotes else null
            }
            is CodeValidationResult.Warning -> {
                _codeStatusMessage.value = vRes.message
            }
        }

        // Determine working array and target
        val array = when (algType) {
            AlgorithmType.BINARY_SEARCH -> currentBsArray
            AlgorithmType.BUBBLE_SORT -> currentBubbleArray
            AlgorithmType.TWO_POINTERS -> currentTpArray
        }

        val target = when (algType) {
            AlgorithmType.BINARY_SEARCH -> currentBsTarget
            AlgorithmType.TWO_POINTERS -> currentTpTarget
            else -> null
        }

        val frames = ExecutionEngine.generateTrace(algType, lang, code, array, target)
        _executionFrames.value = frames
        _currentStepIdx.value = 0
    }

    // --- Accessors for UI ---

    fun getCurrentFrames(): List<ExecutionFrame> = _executionFrames.value

    fun getCurrentFrame(): ExecutionFrame {
        val frames = _executionFrames.value
        if (frames.isEmpty()) {
            return ExecutionFrame(
                stepIndex = 0,
                arraySnapshot = emptyList(),
                activeLineNumber = 1,
                description = "Ready to trace code"
            )
        }
        val idx = _currentStepIdx.value.coerceIn(0, frames.size - 1)
        return frames[idx]
    }

    // Helper to adapt ExecutionFrame to VizStep for existing visualizers
    fun getCurrentStep(): VizStep {
        val f = getCurrentFrame()
        return VizStep(
            array = f.arraySnapshot,
            pointer1 = f.pointer1,
            pointer2 = f.pointer2,
            pointer3 = f.pointer3,
            pointerLabels = f.pointerLabels,
            description = f.description,
            activeLine = (f.activeLineNumber - 1).coerceAtLeast(0),
            isFound = f.isFound,
            isSwap = f.isSwap,
            eliminatedIndices = f.eliminatedIndices,
            variables = f.variables,
            reason = f.reason,
            isCompleted = f.isCompleted
        )
    }

    fun getCurrentSteps(): List<VizStep> {
        return _executionFrames.value.map { f ->
            VizStep(
                array = f.arraySnapshot,
                pointer1 = f.pointer1,
                pointer2 = f.pointer2,
                pointer3 = f.pointer3,
                pointerLabels = f.pointerLabels,
                description = f.description,
                activeLine = (f.activeLineNumber - 1).coerceAtLeast(0),
                isFound = f.isFound,
                isSwap = f.isSwap,
                eliminatedIndices = f.eliminatedIndices,
                variables = f.variables,
                reason = f.reason,
                isCompleted = f.isCompleted
            )
        }
    }

    // --- Custom Input Panel ---

    fun toggleInputEditor() {
        _isInputEditorOpen.value = !_isInputEditorOpen.value
        if (_isInputEditorOpen.value) {
            updateInputTextFields()
        }
    }

    fun closeInputEditor() {
        _isInputEditorOpen.value = false
        _inputError.value = null
    }

    fun onArrayInputChanged(text: String) {
        _customArrayInput.value = text
        _inputError.value = null
    }

    fun onTargetInputChanged(text: String) {
        _customTargetInput.value = text
        _inputError.value = null
    }

    fun applyCustomInput() {
        val algType = getAlgorithmType()
        when (val res = InputValidator.validate(_customArrayInput.value, _customTargetInput.value, algType, autoSortIfRequired = true)) {
            is ValidationResult.Error -> {
                _inputError.value = res.message
            }
            is ValidationResult.Success -> {
                when (_selectedAlg.value) {
                    0 -> {
                        currentBsArray = res.array
                        currentBsTarget = res.target ?: currentBsTarget
                    }
                    1 -> {
                        currentBubbleArray = res.array
                    }
                    else -> {
                        currentTpArray = res.array
                        currentTpTarget = res.target ?: currentTpTarget
                    }
                }
                _inputError.value = null
                _isInputEditorOpen.value = false
                updateInputTextFields()
                runAndVisualizeCode()
            }
        }
    }

    fun randomizeInput() {
        when (_selectedAlg.value) {
            0 -> {
                val size = Random.nextInt(6, 10)
                val set = mutableSetOf<Int>()
                while (set.size < size) {
                    set.add(Random.nextInt(1, 99))
                }
                currentBsArray = set.sorted()
                currentBsTarget = if (Random.nextBoolean()) currentBsArray.random() else Random.nextInt(1, 99)
            }
            1 -> {
                val size = Random.nextInt(5, 8)
                currentBubbleArray = List(size) { Random.nextInt(5, 60) }
            }
            else -> {
                val size = Random.nextInt(6, 9)
                val set = mutableSetOf<Int>()
                while (set.size < size) {
                    set.add(Random.nextInt(1, 50))
                }
                currentTpArray = set.sorted()
                currentTpTarget = currentTpArray.random() + currentTpArray.random()
            }
        }
        updateInputTextFields()
        runAndVisualizeCode()
    }

    // --- Playback Controls ---

    fun togglePlayPause() {
        if (_isPlaying.value) {
            pause()
        } else {
            play()
        }
    }

    fun play() {
        _isPlaying.value = true
        autoPlayJob?.cancel()
        autoPlayJob = viewModelScope.launch {
            val list = _executionFrames.value
            while (_currentStepIdx.value < list.size - 1 && _isPlaying.value) {
                delay((1200 / _speed.value).toLong())
                _currentStepIdx.value++
            }
            _isPlaying.value = false
        }
    }

    fun pause() {
        _isPlaying.value = false
        autoPlayJob?.cancel()
    }

    fun stepNext() {
        val list = _executionFrames.value
        if (_currentStepIdx.value < list.size - 1) {
            _currentStepIdx.value++
        }
    }

    fun stepPrev() {
        if (_currentStepIdx.value > 0) {
            _currentStepIdx.value--
        }
    }

    fun reset() {
        pause()
        _currentStepIdx.value = 0
    }

    fun toggleSpeed() {
        _speed.value = when (_speed.value) {
            1f -> 2f
            2f -> 0.5f
            else -> 1f
        }
    }

    fun completeVisualizerActivity(slug: String) {
        viewModelScope.launch {
            learningRepository.completeLesson(3)
        }
    }

    // --- Gemini AI Ally Integration ---

    fun openAiSheet(actionType: String = "EXPLAIN_STEP") {
        _selectedAiAction.value = actionType
        _isAiSheetOpen.value = true
        requestAiExplanation(actionType)
    }

    fun closeAiSheet() {
        _isAiSheetOpen.value = false
    }

    fun requestAiExplanation(actionType: String, customQuestion: String = "") {
        _selectedAiAction.value = actionType
        _aiLoading.value = true
        _aiError.value = null

        val currentMeta = algMetadata.getOrElse(_selectedAlg.value) { algMetadata[0] }
        val currFrame = getCurrentFrame()
        val totalSteps = _executionFrames.value.size

        val targetVal = when (_selectedAlg.value) {
            0 -> currentBsTarget
            2 -> currentTpTarget
            else -> null
        }

        val request = VisualizerAiRequest(
            algorithm = currentMeta.name,
            slug = currentMeta.slug,
            array = currFrame.arraySnapshot,
            target = targetVal,
            currentStep = _currentStepIdx.value + 1,
            totalSteps = totalSteps,
            description = currFrame.description,
            reason = currFrame.reason,
            activeLine = currFrame.activeLineNumber,
            codeSnippet = currFrame.activeLineCode,
            variables = currFrame.variables,
            actionType = actionType,
            userQuestion = customQuestion
        )

        viewModelScope.launch {
            aiRepository.explainStep(request).fold(
                onSuccess = { data ->
                    _aiLoading.value = false
                    _aiResponse.value = data
                },
                onFailure = { err ->
                    _aiLoading.value = false
                    _aiError.value = err.message ?: "Failed to get AI guidance"
                }
            )
        }
    }
}
