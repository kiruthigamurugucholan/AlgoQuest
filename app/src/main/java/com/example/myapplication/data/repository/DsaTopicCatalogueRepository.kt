    fun getAllCategories(): List<DsaCategory> = categories

    fun getAllSubtopics(): List<DsaSubtopic> = subtopics

    fun getCategoryById(id: String): DsaCategory? = categories.firstOrNull { it.id == id }

    fun getSubtopicsForCategory(categoryId: String): List<DsaSubtopic> =
        subtopics.filter { it.categoryId == categoryId }.sortedBy { it.orderIndex }

    fun getSubtopicById(id: String): DsaSubtopic? = subtopics.firstOrNull { it.id == id }

    fun filterSubtopics(difficulty: TopicDifficulty?): List<DsaSubtopic> =
        if (difficulty == null) subtopics else subtopics.filter { it.difficulty == difficulty }

    fun searchSubtopics(query: String): List<DsaSubtopic> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return subtopics
        return subtopics.filter {
            it.name.lowercase().contains(q) ||
                    it.description.lowercase().contains(q) ||
                    it.id.lowercase().contains(q)
        }
    }
